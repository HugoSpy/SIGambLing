// Backward-compat aliases used by plinko.service.ts
export type RiskLevel = PlinkoRisk;

export function getMultipliers(rows: number, risk: RiskLevel): number[] {
  const table = PLINKO_MULTIPLIERS[risk][rows];
  if (!table) throw new Error(`No multiplier table for rows=${rows}, risk=${risk}`);
  return table;
}
